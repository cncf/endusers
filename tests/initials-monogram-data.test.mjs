import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';

import { initials } from '../src/components/shared/initials.js';

// `initials()` builds the two-letter monogram shown in place of a missing
// logo, at three call sites: `MemberCard` and `MemberProfile` render
// `initials(member.name)` from data/members.json, and `ReferenceArchitectures`
// renders `initials(organization)` from data/architectures/catalog.json.
//
// It takes `part[0]` of each of the first two words, which is one UTF-16 code
// unit, and then uppercases the pair. Two kinds of name break the "two-letter
// monogram" its docstring promises:
//
//   * a first character outside the BMP -- an emoji, or a styled Latin letter
//     such as U+1D400 -- is a surrogate pair, so `part[0]` keeps only the high
//     half and the badge renders a replacement character;
//   * a first character whose uppercase form is longer than itself -- "ß"
//     becomes "SS", "ﬁ" becomes "FI" -- yields a three-character monogram in a
//     fixed-size badge.
//
// Neither coverage lane can see either one. The helper is at 100.00% lines and
// 100.00% regions in both: `src/components/shared/initials.js` reports
// 100.00/100.00 in the unit report (`npm run test:unit:coverage`), and
// 100.00/100.00 in the e2e one (run 38635988670, merge_group at
// 1ae340352d8708a8a1e05c5ad3f400fe7e892b21, artifact `e2e-coverage`,
// coverage/e2e/report.txt line 25). Every name executes the same five lines
// and the same regions, so the only thing that distinguishes a well-formed
// monogram from a broken one is its value.
//
// The existing assertions on the helper, in tests/member-directory.test.mjs
// and tests/reference-architectures.test.mjs, all pass ASCII names, and so
// does every name in data/ today. That is the part worth guarding: neither
// file is hand-written. members.json is generated by
// scripts/generate-members.mjs from the CNCF landscape, and the organization
// names in catalog.json arrive through the architecture submission flow.
// Nothing in either path constrains a name to characters the monogram builder
// can handle, so the first such name would land in a scheduled refresh and
// reach the page without anything failing.
//
// This file is that gate. It asserts the property over the real data rather
// than over fixtures, so it fails on the commit that introduces such a name
// instead of after someone notices a broken badge.
//
// It gates the data, not the helper: a name that cannot produce a monogram
// fails here, but `initials()` itself still mishandles one if it is passed in
// directly. Fixing the helper is #1678, and the two cases above are the
// assertions to revisit when it lands -- the fix makes them well-formed, so
// they move from the rejected list to the accepted one.

const repoRoot = new URL('..', import.meta.url);

function readJson(relativePath) {
  return JSON.parse(readFileSync(new URL(relativePath, repoRoot), 'utf8'));
}

// A high surrogate not followed by a low one, or a low surrogate not preceded
// by a high one. Either half alone is an unpaired code unit, which is what
// slicing a surrogate pair with `[0]` leaves behind.
const UNPAIRED_SURROGATE =
  /[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/u;

/**
 * Describes how `initials(name)` fails to be a monogram, or returns null when
 * it is one. Counted in code points rather than code units: a BMP-only
 * monogram such as "日製" is two characters in both, and the distinction is
 * exactly what the first rule above turns on.
 */
function monogramProblem(name) {
  const monogram = initials(name);
  if (UNPAIRED_SURROGATE.test(monogram))
    return `contains an unpaired surrogate (${JSON.stringify(monogram)})`;
  if ([...monogram].length > 2)
    return `is longer than two characters (${JSON.stringify(monogram)})`;
  return null;
}

// Without this, the two data tests below would still pass if
// monogramProblem() returned null for everything -- including if a refactor of
// the regex above stopped matching -- and the file would be asserting nothing.
// The three accepted names cover the shapes data/ actually holds today: a
// two-word Latin name, a single-word one, and a non-Latin BMP name whose
// monogram is correct.
test('monogramProblem rejects the broken shapes and accepts the real ones', () => {
  for (const name of ['𝐀cme Corp', '🚀 Rocket Labs']) {
    assert.match(
      String(monogramProblem(name)),
      /unpaired surrogate/,
      `${JSON.stringify(name)} must be reported as an unpaired surrogate`,
    );
  }
  for (const name of ['ßeta gmbh', 'ﬁdelity corp']) {
    assert.match(
      String(monogramProblem(name)),
      /longer than two characters/,
      `${JSON.stringify(name)} must be reported as an over-long monogram`,
    );
  }
  for (const name of ['Acme Corp', 'Spotify', '日立 製作所']) {
    assert.equal(
      monogramProblem(name),
      null,
      `${JSON.stringify(name)} is a name data/ already holds and must be accepted`,
    );
  }
});

test('every member name renders a well-formed monogram', () => {
  const { members } = readJson('data/members.json');
  assert.ok(members.length > 0, 'data/members.json carries no members');
  for (const member of members) {
    const problem = monogramProblem(member.name);
    assert.equal(
      problem,
      null,
      `members.json: the monogram for "${member.name}" ${problem}`,
    );
  }
});

test('every architecture organization renders a well-formed monogram', () => {
  const catalog = readJson('data/architectures/catalog.json');
  assert.ok(catalog.length > 0, 'the architecture catalog is empty');
  for (const architecture of catalog) {
    const problem = monogramProblem(architecture.organization);
    assert.equal(
      problem,
      null,
      `catalog.json: the monogram for "${architecture.organization}" ${problem}`,
    );
  }
});
