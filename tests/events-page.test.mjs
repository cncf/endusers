// Source-side contract for the pages under docs/events/: the `/events` index
// the navbar links to and the per-event pages ADR 0012 introduces. A markdown
// doc has no executable lines, so the coverage report cannot see a gap here;
// these assertions are the build-time dependencies the pages carry (a
// `require()`-ed hero image, internal link targets, the component imports the
// index relies on) plus the frontmatter the navbar and search rely on.
//
// Event metadata (dates, location, url, year directory) is the contract of
// scripts/lib/events-catalog.mjs and is asserted in tests/events-catalog.test.mjs;
// this file does not restate it.

import assert from 'node:assert/strict';
import test from 'node:test';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { splitFrontMatter } from '../scripts/lib/architecture-frontmatter.mjs';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const docsRoot = join(repoRoot, 'docs');
const eventsDir = join(docsRoot, 'events');
const indexDoc = join(eventsDir, 'index.md');

function loadDoc(file) {
  const { data, body } = splitFrontMatter(readFileSync(file, 'utf8'));
  assert.ok(data, `${relative(repoRoot, file)} has no front matter mapping`);
  return { file, rel: relative(repoRoot, file), data, body };
}

const index = loadDoc(indexDoc);

test('the index is a listed route with the frontmatter the navbar relies on', () => {
  assert.ok(index.data.title, 'docs/events/index.md needs a title');
  assert.ok(
    index.data.description,
    'docs/events/index.md needs a description; it is the meta description for /events',
  );

  // The navbar's docSidebar item lands on the first sidebar entry, which is
  // this doc, so it must not be unlisted: an unlisted doc is dropped from the
  // sidebar and search index.
  assert.notEqual(
    index.data.unlisted,
    true,
    'the navbar lands on /events, so the doc cannot be unlisted',
  );
  // sidebars.js lists `events/index` first by id, so position is informative
  // only; it still has to sort ahead of the year categories if the sidebar
  // were ever autogenerated.
  assert.equal(index.data.sidebar_position, 1);
});

test('the index renders the catalog through EventsIndex and lists no event itself', () => {
  // The events live on their own pages (ADR 0012); the index is the intro
  // paragraph plus the component that renders the plugin's global data. An
  // event heading or dateline typed here would be a second, unordered copy.
  assert.match(
    index.body,
    /^import EventsIndex from '@site\/src\/components\/EventsIndex';$/m,
    'docs/events/index.md must import EventsIndex',
  );
  assert.match(index.body, /^<EventsIndex \/>$/m);
  assert.doesNotMatch(
    index.body,
    /^##\s+(Upcoming|Past)\b/m,
    'the Upcoming/Past split was retired by ADR 0012',
  );
  assert.doesNotMatch(
    index.body,
    /\*\*(January|February|March|April|May|June|July|August|September|October|November|December)\s+\d/,
    'an event dateline belongs on the event page, not the index',
  );
});

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) return walk(full);
    return /\.mdx?$/.test(entry) ? [full] : [];
  });
}

function normalizeRoute(route) {
  const withoutFragment = route.split('#')[0].split('?')[0];
  if (withoutFragment === '/' || withoutFragment === '') return '/';
  return withoutFragment.replace(/\/+$/, '');
}

// Mirrors the Docusaurus docs-plugin route derivation for routeBasePath '/',
// the same way tests/site-config.test.mjs does: an explicit frontmatter slug
// wins, otherwise the path relative to docs/ is used, with index files
// collapsing onto their containing directory. Restated rather than imported so
// that an unintended change fails in both places.
function routeForDoc(file) {
  const text = readFileSync(file, 'utf8');
  const matched = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const slug = matched ? /^slug:\s*(\S+)\s*$/m.exec(matched[1]) : null;
  if (slug) {
    const value = slug[1].replace(/^['"]|['"]$/g, '');
    if (value.startsWith('/')) return normalizeRoute(value);
  }
  const rel = relative(docsRoot, file).replace(/\\/g, '/');
  return normalizeRoute(
    `/${rel.replace(/\.mdx?$/, '').replace(/(^|\/)index$/, '')}`,
  );
}

const docRoutes = new Set(walk(docsRoot).map(routeForDoc));

// Every page under docs/events/: the index and each event page.
const eventPages = walk(eventsDir).map(loadDoc);

test('docs/events/ holds the index and at least one event page', () => {
  assert.ok(eventPages.some((doc) => doc.file === indexDoc));
  assert.ok(
    eventPages.some((doc) => doc.file !== indexDoc),
    'no event page found under docs/events/<year>/',
  );
});

test('every @site asset an events page requires exists on disk', () => {
  // `require('@site/static/img/...').default` is resolved by webpack during
  // the Docusaurus build, so a renamed or deleted asset fails the build rather
  // than degrading. Nothing else in the suite reads these pages' asset
  // references.
  const required = eventPages.flatMap((doc) =>
    [...doc.body.matchAll(/require\(\s*['"]@site\/([^'"]+)['"]\s*\)/g)].map(
      ([, path]) => `${doc.rel} -> ${path}`,
    ),
  );
  assert.ok(
    required.length > 0,
    'no @site asset reference found; this contract needs updating if the pages stopped embedding one',
  );
  const missing = required.filter(
    (entry) => !existsSync(join(repoRoot, entry.split(' -> ')[1])),
  );
  assert.deepEqual(missing, [], 'events pages require missing assets');
});

test('every internal link on an events page resolves to a doc route', () => {
  // Covers both idioms the pages use: `<Link to="/...">` in JSX and
  // `[text](/...)` in markdown. The link-hygiene lint rules in eslint.config.mjs
  // cover only sources under src/, so nothing validated these.
  const targets = eventPages.flatMap((doc) => [
    ...[...doc.body.matchAll(/<Link\s+[^>]*to=["'](\/[^"'#]*)/g)].map(
      ([, to]) => `${doc.rel} -> ${to}`,
    ),
    ...[...doc.body.matchAll(/\]\(\s*(\/[^)\s#]*)/g)].map(
      ([, to]) => `${doc.rel} -> ${to}`,
    ),
  ]);

  assert.ok(
    targets.length > 0,
    'no internal link found; this contract needs updating if the pages stopped linking into the site',
  );

  const broken = targets.filter(
    (entry) => !docRoutes.has(normalizeRoute(entry.split(' -> ')[1])),
  );
  assert.deepEqual(broken, [], 'events pages link to routes no doc serves');
});
