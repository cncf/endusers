#!/usr/bin/env node
// Collects the current CNCF case study catalog from the public cncf.io
// WordPress REST API and writes data/case-studies.json. Run manually with
// `npm run collect:case-studies` (there is no scheduled workflow for this
// yet) so the /resources/case-studies table mirrors
// https://www.cncf.io/case-studies/.
//
// Each case study's descriptive headline (e.g. "Zynga Scales Gaming
// Infrastructure by Eliminating Networking Bottlenecks with Cilium") is
// published by cncf.io as post meta (`lf_case_study_long_title`), separate
// from the post title, which is just the organization name.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const API = 'https://www.cncf.io/wp-json/wp/v2';
const SOURCE_URL = 'https://www.cncf.io/case-studies/';

async function fetchAllPages(path) {
  const results = [];
  let page = 1;
  for (;;) {
    const response = await fetch(
      `${API}/${path}${path.includes('?') ? '&' : '?'}per_page=100&page=${page}`,
    );
    if (!response.ok) {
      if (response.status === 400 && page > 1) break; // past the last page
      throw new Error(`cncf.io API ${response.status}: ${path} (page ${page})`);
    }
    const batch = await response.json();
    results.push(...batch);
    const totalPages = Number(response.headers.get('x-wp-totalpages') || '1');
    if (page >= totalPages || !batch.length) break;
    page += 1;
  }
  return results;
}

async function fetchTermNames(taxonomy) {
  const terms = await fetchAllPages(taxonomy);
  return new Map(terms.map((term) => [term.id, term.name]));
}

function namesFor(ids, termMap) {
  return (ids || [])
    .map((id) => termMap.get(id))
    .filter(Boolean)
    .sort();
}

function decodeEntities(text) {
  return text
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&amp;/g, '&')
    .replace(/&#8217;/g, '\u2019')
    .replace(/&#8211;/g, '\u2013')
    .replace(/&#8212;/g, '\u2014');
}

const [projects, industries, countries, caseStudyPosts] = await Promise.all([
  fetchTermNames('lf-project'),
  fetchTermNames('lf-industry'),
  fetchTermNames('lf-country'),
  fetchAllPages(
    'lf_case_study?_fields=id,slug,link,title,date,meta,lf-project,lf-industry,lf-country',
  ),
]);

const caseStudies = caseStudyPosts
  .map((post) => {
    const organization = decodeEntities(
      post.title?.rendered?.trim() || post.slug,
    );
    const longTitle = post.meta?.lf_case_study_long_title?.trim();
    return {
      id: post.id,
      title: longTitle ? decodeEntities(longTitle) : organization,
      organization,
      slug: post.slug,
      url: post.link,
      publishedAt: post.date ? post.date.slice(0, 10) : null,
      projects: namesFor(post['lf-project'], projects),
      industries: namesFor(post['lf-industry'], industries),
      countries: namesFor(post['lf-country'], countries),
    };
  })
  .sort((a, b) => a.organization.localeCompare(b.organization));

const generatedAt = new Date().toISOString();
const data = {
  description:
    'CNCF end-user case studies mirrored from cncf.io for /resources/case-studies. Regenerated by running `npm run collect:case-studies` (scripts/collect-case-studies.mjs); there is no scheduled workflow yet, so a maintainer re-runs it manually; do not hand-edit entries here, edit the source on cncf.io instead.',
  generatedAt,
  source: 'cncf.io case studies',
  sourceUrl: SOURCE_URL,
  apiUrl: `${API}/lf_case_study`,
  caseStudies,
};

mkdirSync(join(root, 'data'), { recursive: true });
writeFileSync(
  join(root, 'data/case-studies.json'),
  JSON.stringify(data, null, 2) + '\n',
);
console.log(`Collected ${caseStudies.length} case studies at ${generatedAt}`);
