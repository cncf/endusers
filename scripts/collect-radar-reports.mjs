#!/usr/bin/env node
// Collects the current CNCF Radar reports from the public cncf.io WordPress
// REST API and writes data/radar-reports.json. Run on a daily schedule by
// .github/workflows/refresh-radar-reports.yml so /resources/radar-reports
// stays in sync with https://www.cncf.io/reports?_sft_lf-report-type=radar.
//
// cncf.io does not publish an excerpt for these reports, so each entry keeps
// a short hand-written `summary`. Existing summaries are preserved across
// refreshes (matched by report id); new reports get a placeholder summary
// that a maintainer should replace with a real one-sentence description in
// the PR the refresh workflow opens.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeEntities, fetchAllPages } from './lib/cncf-wp-api.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const API = 'https://www.cncf.io/wp-json/wp/v2';
const SOURCE_URL = 'https://www.cncf.io/reports?_sft_lf-report-type=radar';
const PLACEHOLDER_SUMMARY = 'Summary needed — see the report for details.';

const reportTypes = await fetchAllPages(API, 'lf-report-type');
const radarType = reportTypes.find((term) => term.slug === 'radar');
if (!radarType)
  throw new Error(
    'cncf.io no longer exposes an lf-report-type term with slug "radar"',
  );

const existingPath = join(root, 'data/radar-reports.json');
const existingSummaries = new Map();
let existingRadarReports = [];
if (existsSync(existingPath)) {
  const existing = JSON.parse(readFileSync(existingPath, 'utf8'));
  existingRadarReports = existing.radarReports || [];
  for (const report of existingRadarReports) {
    if (report.summary) existingSummaries.set(report.id, report.summary);
  }
}

const posts = await fetchAllPages(
  API,
  `lf_report?lf-report-type=${radarType.id}&_fields=id,slug,link,title,date`,
);

const radarReports = posts
  .map((post) => ({
    id: post.id,
    title: decodeEntities(post.title?.rendered?.trim() || post.slug),
    slug: post.slug,
    url: post.link,
    publishedAt: post.date ? post.date.slice(0, 10) : null,
    summary: existingSummaries.get(post.id) || PLACEHOLDER_SUMMARY,
  }))
  .sort((a, b) => (b.publishedAt || '').localeCompare(a.publishedAt || ''));

// Only bump generatedAt and rewrite the catalog when the reports themselves
// changed. cncf.io content is checked daily but rarely changes day to day, so
// touching generatedAt on every run would open a no-op refresh PR each time
// (see #648).
if (
  existsSync(existingPath) &&
  JSON.stringify(radarReports) === JSON.stringify(existingRadarReports)
) {
  console.log('No radar report changes detected; leaving catalog untouched.');
  process.exit(0);
}

const generatedAt = new Date().toISOString();
const data = {
  description:
    'CNCF Technology Radar reports mirrored from cncf.io for /resources/radar-reports. Regenerated by scripts/collect-radar-reports.mjs via the refresh-radar-reports workflow (daily). `summary` is hand-written and preserved across refreshes; fill in PLACEHOLDER summaries in the automation PR.',
  generatedAt,
  source: 'cncf.io reports (Radar type)',
  sourceUrl: SOURCE_URL,
  apiUrl: `${API}/lf_report?lf-report-type=${radarType.id}`,
  radarReports,
};

mkdirSync(join(root, 'data'), { recursive: true });
writeFileSync(
  join(root, 'data/radar-reports.json'),
  JSON.stringify(data, null, 2) + '\n',
);
console.log(`Collected ${radarReports.length} radar reports at ${generatedAt}`);
