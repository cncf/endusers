#!/usr/bin/env node
// Collects the current CNCF Radar reports from the public cncf.io WordPress
// REST API and writes data/radar-reports.json. Run manually with
// `npm run collect:radar-reports` (there is no scheduled workflow for this
// yet) so /resources/radar-reports stays in sync with
// https://www.cncf.io/reports?_sft_lf-report-type=radar.
//
// cncf.io does not publish an excerpt for these reports, so each entry keeps
// a short hand-written `summary`. Existing summaries are preserved across
// refreshes (matched by report id); new reports get a placeholder summary
// that a maintainer should replace with a real one-sentence description
// before merging the refresh.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const API = 'https://www.cncf.io/wp-json/wp/v2';
const SOURCE_URL = 'https://www.cncf.io/reports?_sft_lf-report-type=radar';
const PLACEHOLDER_SUMMARY = 'Summary needed — see the report for details.';

async function fetchAllPages(path) {
  const results = [];
  let page = 1;
  for (;;) {
    const response = await fetch(
      `${API}/${path}${path.includes('?') ? '&' : '?'}per_page=100&page=${page}`,
    );
    if (!response.ok) {
      if (response.status === 400 && page > 1) break;
      throw new Error(`cncf.io API ${response.status}: ${path} (page ${page})`);
    }
    const batch = await response.json();
    results.push(...batch);
    const totalPages = Number(response.headers.get('x-wp-totalpages') || '1');
    if (page >= totalPages || !batch.length) break;
    page += 1;
  }
  return results;
}

const reportTypes = await fetchAllPages('lf-report-type');
const radarType = reportTypes.find((term) => term.slug === 'radar');
if (!radarType)
  throw new Error(
    'cncf.io no longer exposes an lf-report-type term with slug "radar"',
  );

const existingPath = join(root, 'data/radar-reports.json');
const existingSummaries = new Map();
if (existsSync(existingPath)) {
  const existing = JSON.parse(readFileSync(existingPath, 'utf8'));
  for (const report of existing.radarReports || []) {
    if (report.summary) existingSummaries.set(report.id, report.summary);
  }
}

const posts = await fetchAllPages(
  `lf_report?lf-report-type=${radarType.id}&_fields=id,slug,link,title,date`,
);

function decodeEntities(text) {
  return text
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&amp;/g, '&')
    .replace(/&#8217;/g, '\u2019')
    .replace(/&#8211;/g, '\u2013')
    .replace(/&#8212;/g, '\u2014');
}

const radarReports = posts
  .map((post) => ({
    id: post.id,
    title: decodeEntities(post.title?.rendered?.trim() || post.slug),
    slug: post.slug,
    url: post.link,
    publishedAt: post.date ? post.date.slice(0, 10) : null,
    summary: existingSummaries.get(post.id) || PLACEHOLDER_SUMMARY,
  }))
  .sort((a, b) => (b.publishedAt || '').localeCompare(a.publishedAt || ''));

const generatedAt = new Date().toISOString();
const data = {
  description:
    'CNCF Technology Radar reports mirrored from cncf.io for /resources/radar-reports. Regenerated by running `npm run collect:radar-reports` (scripts/collect-radar-reports.mjs); there is no scheduled workflow yet, so a maintainer re-runs it manually. `summary` is hand-written and preserved across refreshes; fill in PLACEHOLDER summaries before merging.',
  generatedAt,
  source: 'cncf.io reports (Radar type)',
  sourceUrl: SOURCE_URL,
  apiUrl: `${API}/lf_report?lf-report-type=${radarType.id}`,
  radarReports,
};

mkdirSync(join(root, 'data'), { recursive: true });
writeFileSync(
  join(root, 'data/radar-reports.json'),
  JSON.stringify(data, null, 2) + '\n',
);
console.log(`Collected ${radarReports.length} radar reports at ${generatedAt}`);
